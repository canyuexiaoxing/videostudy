import {createPackage,extractAll,extractFile} from '../../../desktop/node_modules/@electron/asar/lib/asar.js';
import {readFile,writeFile,mkdir,cp,copyFile,rename} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import crypto from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../..');
const latest=JSON.parse(await readFile(path.join(root,'.local/releases/latest.json'),'utf8'));
const archive=path.resolve(latest.folder,'resources/app.asar');
if(!archive.startsWith(path.join(root,'.local/releases')+path.sep))throw Error('unexpected_application_path');
const stamp=new Date().toISOString().replace(/[:.]/g,'-');
const out=path.join(root,'.local/qa/direct-only',stamp),stage=path.join(out,'app');
await mkdir(stage,{recursive:true});extractAll(archive,stage);
await cp(path.join(root,'desktop/dist'),path.join(stage,'dist'),{recursive:true});
const prepared=path.join(out,'app.asar');await createPackage(stage,prepared);
const hash=data=>crypto.createHash('sha256').update(data).digest('hex');
if(hash(extractFile(prepared,'dist/index.html'))!==hash(await readFile(path.join(root,'desktop/dist/index.html'))))throw Error('prepared_frontend_mismatch');
const report={prepared,archive,previousSha256:hash(await readFile(archive)),preparedSha256:hash(await readFile(prepared)),installed:false,paidCalls:0};
await writeFile(path.join(root,'.local/qa/direct-only/prepared.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report));
